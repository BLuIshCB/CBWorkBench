import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { CliRunner } from '../src/services/cliRunner.ts';
import { TestRunner } from '../src/services/testRunner.ts';
import { db } from '../src/storage/db.ts';
import { executionTimeoutSchema, resolveExecutionTimeout } from '../src/services/executionPolicy.ts';
import { createHttpServer } from '../src/server/httpServer.ts';
import path from 'node:path';

assert.equal(resolveExecutionTimeout(undefined,60000),60000);
assert.equal(resolveExecutionTimeout(120000,60000),120000);
assert.equal(resolveExecutionTimeout(undefined,null,{executionPolicy:{executionTimeoutMs:180000,timeoutMs:60000}}),180000);
for(const value of [0,-1,60001,86460000,Infinity,NaN,'60000']) assert.equal(executionTimeoutSchema.safeParse(value).success,false);

const taskId='execution-'+randomUUID();
const task=db.createTask({id:taskId,task_key:taskId,title:'Execution governance fixture',target_cwd:process.cwd(),execution_timeout_ms:60000});
assert.equal(task.execution_timeout_ms,60000);
assert.equal(task.worker_executor,'codex');
assert.equal(task.worker_model,'default');
const runId=randomUUID();
const controller=new AbortController();
const execution=CliRunner.run({runId,taskId,executable:process.execPath,args:['-e','process.stdout.write("实时中文😀");setInterval(()=>{},1000)'],cwd:process.cwd(),timeoutMs:5000,signal:controller.signal});
const server=createHttpServer();
await new Promise<void>(resolve=>server.listen(0,'127.0.0.1',resolve));
const base='http://127.0.0.1:'+(server.address() as any).port;
try {
  const deadline=Date.now()+3000;
  while(!db.runEvents(runId,0,500).some(e=>e.type==='output') && Date.now()<deadline) await new Promise(resolve=>setTimeout(resolve,20));
  assert.ok(db.runEvents(runId,0,500).some(e=>e.data.text==='实时中文😀'),'Output must be persisted while the process is alive');
  assert.equal(db.getRun(runId)?.finishedAt,null);
  const page=await fetch(base+'/api/runs/'+runId+'/events?after=0&limit=1').then(r=>r.json());
  assert.equal(page.events.length,1);assert.equal(page.nextAfter,1);assert.equal(page.hasMore,true);
  const stream=await fetch(base+'/api/runs/'+runId+'/stream?after=0');
  const reader=stream.body!.getReader();
  const first=await reader.read();assert.ok(new TextDecoder().decode(first.value).includes('event: execution'));
  await reader.cancel();
  assert.equal(db.getRun(runId)?.finishedAt,null,'Disconnect must not terminate the process');
  for(const query of ['after=-1','after=1e3','limit=501']) assert.equal((await fetch(base+'/api/runs/'+runId+'/events?'+query)).status,400);
  assert.equal((await fetch(base+'/api/runs/'+runId+'/stream?after=0',{headers:{'Last-Event-ID':'invalid'}})).status,400);
  assert.equal((await fetch(base+'/api/tasks/'+taskId+'/confirm-start',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({execution_timeout_ms:60001})})).status,400);
  controller.abort();
  const result=await execution;
  assert.equal(result.stopReason,'USER_CANCELLED');assert.equal(result.cleanupConfirmed,true);
  const events=db.runEvents(runId,0,500);assert.equal(events.at(-1)?.type,'finished');
  const resumed=await fetch(base+'/api/runs/'+runId+'/stream?after=0',{headers:{'Last-Event-ID':String(events.at(-1)!.seq)}});
  assert.equal(await resumed.text(),'','Last-Event-ID takes priority and a terminal cursor closes without replay');
  assert.equal(db.getRun(runId)?.state,'cancelled');
  assert.deepEqual(events.map(e=>e.seq),events.map((_,index)=>index+1));
  const tests=await TestRunner.runAllTests([{id:'timeout',command:'"'+process.execPath+'" -e "setInterval(()=>{},1000)"'},{id:'must-not-run',command:'echo unexpected'}],process.cwd(),200,{taskId});
  assert.equal(tests.interrupted,true);assert.equal(tests.testRuns.length,1);
  assert.equal(CliRunner.hasUncleanRuns(),false);
  let treeOutput='';
  const treeController=new AbortController();
  const tree=CliRunner.run({runId:randomUUID(),taskId,executable:process.execPath,args:[path.resolve('tests/fixtures/process-tree.mjs')],cwd:process.cwd(),timeoutMs:10000,signal:treeController.signal,onChunk:chunk=>{treeOutput+=chunk.text;}});
  const treeDeadline=Date.now()+3000;
  while(!treeOutput.includes('\n') && Date.now()<treeDeadline)await new Promise(resolve=>setTimeout(resolve,20));
  assert.ok(treeOutput.includes('childPid'));
  const {childPid}=JSON.parse(treeOutput.trim());
  treeController.abort();
  const treeResult=await tree;
  assert.equal(treeResult.stopReason,'USER_CANCELLED');assert.equal(treeResult.cleanupConfirmed,true);
  assert.throws(()=>process.kill(childPid,0),'The descendant must be terminated with its parent');
  const expiredId=randomUUID();
  db.saveRun({...db.getRun(runId)!,runId:expiredId,taskId:null,finishedAt:Date.now()-8*86400000});
  await CliRunner.run({runId:randomUUID(),executable:process.execPath,args:['-e','process.stdout.write("probe")'],cwd:process.cwd(),timeoutMs:5000});
  assert.equal(db.getRun(expiredId),null,'Finished probe retention must also run at completion');
} finally {
  controller.abort();await execution;
  server.closeAllConnections();await new Promise<void>(resolve=>server.close(()=>resolve()));
  db.deleteTask(taskId);
}
console.log('✅ executionGovernance.test.ts passed');
